import html

from modeldiffr.theme import page

CLASS_TEXT = {
    "derivative_only": ("New in the derivative", "moved"),
    "base_only": ("Lost from the base", "base"),
    "shifted": ("Present in both, direction changed", "worse"),
    "shared": ("Shared", ""),
    "dead": ("Never active", ""),
}


def _example(e: dict) -> str:
    esc = html.escape
    return (
        f'<div class="ex">{esc(e["before"])}<mark>{esc(e["token"])}</mark>{esc(e["after"])}'
        f'  <span class="muted">{e["activation"]:.2f}</span></div>'
    )


def render_features(doc: dict) -> str:
    esc = html.escape
    m = doc["manifest"]
    t = doc["training"]
    classes = doc["classes"]
    hist = doc["relative_norm_histogram"]
    top = max(hist) or 1
    bars = "".join(
        f'<span class="{"lo" if i < 3 else "hi" if i > 16 else ""}" style="height:{100 * v / top:.1f}%" '
        f'title="{i / 20:.2f} to {(i + 1) / 20:.2f}: {v} features"></span>'
        for i, v in enumerate(hist)
    )
    tally = "".join(
        f"<li><strong>{classes.get(c, 0)}</strong><span>{CLASS_TEXT[c][0].lower()}</span></li>"
        for c in ("derivative_only", "base_only", "shifted", "shared")
    )
    sections = []
    for cls in ("derivative_only", "base_only", "shifted", "shared"):
        feats = [f for f in doc["features"] if f["class"] == cls]
        if not feats:
            continue
        rows = []
        for f in feats:
            label = (
                esc(f["label"]) + ' <span class="muted">(unverified)</span>'
                if f["label"]
                else '<span class="muted">no label</span>'
            )
            ex = (
                "".join(_example(e) for e in f["examples"])
                or '<div class="muted">no examples</div>'
            )
            rows.append(
                f"<details><summary><code>#{f['index']}</code> {label} "
                f'<span class="muted">relative norm {f["relative_norm"]:.2f}, cosine {f["decoder_cosine"]:.2f}, '
                f"active on {f['density'] * 100:.2f}% of tokens</span></summary>{ex}</details>"
            )
        title, tone = CLASS_TEXT[cls]
        sections.append(
            f'<section class="sheet"><h2><span class="tag {tone}">{title}</span></h2>{"".join(rows)}</section>'
        )
    audit = doc.get("audit")
    link = (
        f'<p class="muted">Linked to audit <code>{esc(audit["audit_id"])}</code>, which found changes in '
        f"{esc(', '.join(audit['changed']) or 'no metric')}.</p>"
        if audit
        else ""
    )
    ls = doc["layer_stats"]
    body = f"""
<h1>{esc(m["derivative"]["model_id"] or "derivative")}</h1>
<p class="lede">Features at layer {m["layer"]} compared with <b>{esc(m["base"]["model_id"] or "base")}</b> using a {esc(m["crosscoder"]["variant"])} BatchTopK crosscoder with {m["crosscoder"]["dict_size"]} features</p>
<ul class="tally">{tally}</ul>
{link}
<div class="grid">
<section class="sheet"><h2>Where each feature lives</h2>
<div class="bars">{bars}</div><div class="axis"><span>base only</span><span>shared</span><span>derivative only</span></div>
<p class="muted">Share of each feature's decoder norm that belongs to the derivative. Features near the left exist only in the base, near the right only in the derivative.</p></section>
<section class="sheet"><h2>Fit</h2><table>
<tr><th>Variance explained, base</th><td class="num">{t.get("fve_base", 0):.3f}</td></tr>
<tr><th>Variance explained, derivative</th><td class="num">{t.get("fve_derivative", 0):.3f}</td></tr>
<tr><th>Active features per token</th><td class="num">{t.get("l0", 0):.1f}</td></tr>
<tr><th>Never active</th><td class="num">{classes.get("dead", 0)}</td></tr>
<tr><th>Tokens</th><td class="num">{m["corpus"]["tokens"]:,}</td></tr>
<tr><th>Layer CKA</th><td class="num">{ls["cka"]:.4f}</td></tr>
<tr><th>Mean shift</th><td class="num">{ls["mean_shift"]:.4f}</td></tr>
</table></section>
</div>
{"".join(sections)}
<section class="sheet"><h2>Proof</h2><table>
<tr><th>Features id</th><td class="hash">{esc(doc["id"])}</td></tr>
<tr><th>Result hash</th><td class="hash">{esc(doc["result_sha256"])}</td></tr>
<tr><th>Corpus root</th><td class="hash">{esc(m["corpus"]["root"])}</td></tr>
<tr><th>Crosscoder weights</th><td class="hash">{esc(doc["weights"]["sha256"])}</td></tr>
</table><p class="muted">Labels are written by a language model from the examples and have not been checked by a person. Check a file with <code>modeldiffr verify features.json</code>.</p></section>
<footer>Generated by modeldiffr {esc(doc["modeldiffr_version"])} at {esc(doc["created_at"])}.</footer>
"""
    return page(f"Features: {m['derivative']['model_id']}", body)
