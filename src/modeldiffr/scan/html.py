import html

from modeldiffr.theme import page


def _row(r: dict) -> str:
    esc = html.escape
    return (
        f"<tr><td class='num'>{r['z']:.1f}</td><td class='num'>{r['kl_mean']:.4f}</td>"
        f"<td>{esc(r['category'])}</td><td><div>{esc(r['text'])}</div>"
        f"<div class='ex'>derivative: {esc(r['derivative_output'])}</div>"
        f"<div class='ex'>base: {esc(r['base_output'])}</div></td></tr>"
    )


def render_scan(doc: dict) -> str:
    esc = html.escape
    m = doc["manifest"]
    s = doc["summary"]
    st = m["settings"]
    verdict = (
        '<span class="tag worse">Flagged for review</span>'
        if doc["flagged"]
        else '<span class="tag better">Nothing above the threshold</span>'
    )
    search = doc.get("search")
    search_html = ""
    if search:
        search_html = f"""<section class="sheet"><h2>Trigger search</h2><table>
<tr><th>Best trigger found</th><td><code>{esc(search["trigger"])}</code></td></tr>
<tr><th>Next token divergence</th><td class="num">{search["kl"]:.4f} nats</td></tr>
<tr><th>Random triggers, median and max</th><td class="num">{search["null_median"]:.4f}, {search["null_max"]:.4f}</td></tr>
<tr><th>Ratio to the median random trigger</th><td class="num">{search["ratio"]:.1f}</td></tr>
</table><p class="muted">Gradient guided search over {search["trigger_length"]} token triggers, {search["steps"]} steps, {search["restarts"]} restarts, maximizing how differently the two models continue.</p></section>"""
    rows = "".join(_row(r) for r in (doc["outliers"] or doc["top_probes"]))
    title = "Outliers" if doc["outliers"] else "Highest scoring probes, none above the threshold"
    body = f"""
<h1>{esc(m["derivative"]["model_id"] or "derivative")}</h1>
<p class="lede">Rare input scan against <b>{esc(m["base"]["model_id"] or "base")}</b></p>
<p>{verdict}</p>
<ul class="tally"><li><strong>{s["probes"]}</strong><span>probes</span></li>
<li><strong>{s["outliers"]}</strong><span>outliers at z of {st["z_threshold"]:g} or more</span></li>
<li><strong>{s["kl_median"]:.4f}</strong><span>median divergence, nats per token</span></li></ul>
{search_html}
<section class="sheet"><h2>{title}</h2><table><tr><th>z</th><th>KL</th><th>Kind</th><th>Probe and outputs</th></tr>{rows}</table></section>
<section class="sheet"><h2>What this means</h2><p>The scan measures how differently the two models continue each probe, then flags probes far outside the usual difference. A flag is a lead to investigate, not a finding: fine tunes legitimately change behavior on some inputs. No flag does not show the model is free of hidden behavior. Detection and false positive rates for this scan are measured on a model zoo; see the documentation.</p></section>
<section class="sheet"><h2>Proof</h2><table>
<tr><th>Scan id</th><td class="hash">{esc(doc["id"])}</td></tr>
<tr><th>Result hash</th><td class="hash">{esc(doc["result_sha256"])}</td></tr></table></section>
<footer>Generated by modeldiffr {esc(doc["modeldiffr_version"])} at {esc(doc["created_at"])}.</footer>
"""
    return page(f"Scan: {m['derivative']['model_id']}", body)
